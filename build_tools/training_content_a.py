# ============================================================ Part 2 · WHAT
def _pipeline_html() -> str:
    rows = [
        ("explore", "AI", "场景 yml + 元素清单", "cases/ai_*.json · element_maps/*.json", "AI 没排对 / 漏控件", "1~4 分钟"),
        ("generate", "确定性", "cases/*.json", "scripts/generated/*.py + datasets/*.json", "语义名对不上控件", "1~3 秒"),
        ("run", "确定性", "scripts/generated/", "log/latest/report.html + 现场证据", "定位失败 / 断言不成立", "单条 1~7 分钟"),
        ("verify", "确定性", "cases/ 与实跑", "两档校验结论（产出 + 实跑）", "产出不合格 / 实测不过", "同 run"),
    ]
    h = ['<div class="flow">']
    for name, who, inp, outp, fail, cost in rows:
        h.append(f'<div class="flow-step"><div class="tag">{esc_(name)}</div>'
                 f'<h4>{esc_(who)}</h4>'
                 f'<p><b>输入</b>：{esc_(inp)}<br><b>产出</b>：{esc_(outp)}<br>'
                 f'<b>挂在这段的症状</b>：{esc_(fail)}<br><b>耗时量级</b>：{esc_(cost)}</p></div>')
    h.append("</div>")
    return "".join(h)


def esc_(t: str) -> str:
    import html
    return html.escape(str(t), quote=False)


