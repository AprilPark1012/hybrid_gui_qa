def _feature_map(d: Doc) -> None:
    from framework.features.f09_gate.feature_spec import FEATURES
    rows, md_rows = [], []
    for f in FEATURES:
        subs = f.get("subs") or []
        goals = "<br>".join(f"{s['no']} {s['name']}" for s in subs)  # 下方行内已转义
        from build_tools.training_doc import esc as _e, inline_md as _imd
        rows.append([str(f["no"]), B(_e(f["name"])) + "<br><span style='color:#64748b;font-size:.9em'>"
                     + _imd(str(f.get("goal", "")))[:150] + "…</span>",
                     str(len(subs)), _imd(str(goals))])
        md_rows.append([str(f["no"]), f"**{f['name']}**", str(len(subs)),
                        "；".join(f"{s['no']} {s['name']}" for s in subs)])
    d.table(["#", "特性", "子特性", "子特性名"], rows, md=md_rows)
    d.p("每个子特性的「目标 + 判据文件」由单一来源 " + C("framework/features/f09_gate/feature_spec.py")
        + " 渲染成 " + C("docs/feature_map.md") + "，那里可以直接查「这条能力由哪些判据守着」。")
    d.p("下面按特性展开：<b>目标</b>说这条能力保什么，<b>判据</b>说它被哪些测试文件守着"
        "（判据名就是「这条能力挂了会红在哪」）。")

    # 逐特性展开（渲染复用 build_html 里的 feat/subfeat 块 —— 单一来源，不另写一套）
    import build_tools.build_html as _bh
    h = "".join(_bh._feat_block(f) for f in FEATURES)
    md = []
    for f in FEATURES:
        md.append(f"\n### 特性 {f['no']} · {f['name']}")
        md.append(f"目标：{f.get('goal', '')}")
        for s in f.get("subs") or []:
            md.append(f"- **{s['no']} {s['name']}**：{s.get('goal', '')[:160]}")
    d.raw(h, "\n".join(md))


